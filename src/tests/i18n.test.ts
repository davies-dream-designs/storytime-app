function flattenKeys(value: unknown, prefix = ""): string[] {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    return prefix ? [prefix] : [];
  }

  return Object.entries(value).flatMap(([key, child]) =>
    flattenKeys(child, prefix ? `${prefix}.${key}` : key)
  );
}

function readMessages(locale: string) {
  return JSON.parse(
    readFileSync(join(process.cwd(), "messages", `${locale}.json`), "utf8")
  ) as unknown;
}

function flattenMessages(value: unknown, prefix = ""): Record<string, unknown> {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    return prefix ? { [prefix]: value } : {};
  }

  return Object.entries(value).reduce<Record<string, unknown>>(
    (messages, [key, child]) => ({
      ...messages,
      ...flattenMessages(child, prefix ? `${prefix}.${key}` : key),
    }),
    {}
  );
}

describe("i18n messages", () => {
  it("keeps every locale aligned with the English message keys", () => {
    const englishKeys = flattenKeys(readMessages("en")).sort();

    for (const { code } of localeConfigs) {
      const localeKeys = flattenKeys(readMessages(code)).sort();

      expect(localeKeys, `${code}.json keys`).toEqual(englishKeys);
    }
  });

  it("does not leave English fallback text in translated locales", () => {
    const englishMessages = flattenMessages(readMessages("en"));

    for (const { code } of localeConfigs.filter(({ code }) => code !== "en")) {
      const localeMessages = flattenMessages(readMessages(code));
      const identicalKeys = Object.entries(englishMessages)
        .filter(([key, englishValue]) => {
          const localeValue = localeMessages[key];
          return (
            typeof englishValue === "string" &&
            typeof localeValue === "string" &&
            englishValue.trim().length > 0 &&
            englishValue === localeValue &&
            !IDENTICAL_TEXT_ALLOWLIST.has(key)
          );
        })
        .map(([key]) => key)
        .sort();

      expect(identicalKeys, `${code}.json untranslated strings`).toEqual(
        [...(AUDITED_ENGLISH_FALLBACK_BASELINE[code] ?? [])].sort()
      );
    }
  });
});
